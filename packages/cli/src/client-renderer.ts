import { ImportRenderer, isNamedSchemaExpression, joinPaths, renderExpression, type AstControllerNode, type AstExpressionRef, type AstRouteNode } from './ast';

/**
 * Renders a typed HTTP client (`client.ts`) for every route in the app.
 *
 * - Types come from the same sources as `contracts.ts`: schema inputs/outputs via Standard Schema
 *   types, falling back to handler parameter / return types when a route has no schema.
 * - Every import is `import type`, so the file never pulls server code into a frontend bundle.
 * - Methods are grouped by `operationId` (`users.list` -> `client.users.list`), or by controller
 *   and method name when a route has none.
 */
export function renderClient(controllers: AstControllerNode[], outFile: string) {
  const renderer = new ImportRenderer(outFile, true);
  const inferInput = renderer.addTypeImport('@kivin/core', 'InferSchemaInput');
  const inferOutput = renderer.addTypeImport('@kivin/core', 'InferSchemaOutput');
  const groups = new Map<string, Map<string, string>>();
  const operations: string[] = [];

  const schemaType = (controller: AstControllerNode, expression: AstExpressionRef | undefined) => {
    if (!expression) {
      return undefined;
    }
    return isNamedSchemaExpression(expression) ? `typeof ${renderExpression(controller.filePath, expression, renderer)}` : undefined;
  };

  for (const controller of controllers) {
    for (const route of controller.routes) {
      if (route.methodName.startsWith('[')) {
        continue;
      }
      const controllerType = renderer.addNamedImport(controller.filePath, controller.className);
      const handler = `${controllerType}[${JSON.stringify(route.methodName)}]`;
      const fullPath = joinPaths(controller.basePath, route.path);
      const [groupName, methodName] = clientName(controller, route);
      const operationKey = `${groupName}.${methodName}`;

      const parts: string[] = [];
      const params = paramsType(route, fullPath, schemaType(controller, route.paramSchema), inferInput);
      if (params) {
        parts.push(`Part<'params', ${params}>`);
      }
      const query = queryType(route, schemaType(controller, route.querySchema), inferInput);
      if (query) {
        parts.push(`Part<'query', ${query}>`);
      }
      const body = bodyType(route, handler, schemaType(controller, route.bodySchema), inferInput);
      if (body) {
        parts.push(`Part<'body', ${body}>`);
      }
      const headerSchema = schemaType(controller, route.headerSchema);
      if (headerSchema) {
        // Typed (names and values) but optional: required headers are often sent for every request
        // through createClient({ headers }), so a call does not have to repeat them.
        parts.push(`{ headers?: HeadersInput & Partial<${inferInput}<${headerSchema}>> }`);
      }
      const output = outputType(controller, route, handler, schemaType, inferOutput);
      const inputType = parts.length > 0 ? `ClientRequestOptions & ${parts.join(' & ')}` : 'ClientRequestOptions';

      const group = groups.get(groupName) ?? new Map<string, string>();
      if (group.has(methodName)) {
        throw new Error(`client: two routes map to ${operationKey}; give them distinct @OperationId values`);
      }
      groups.set(groupName, group);
      operations.push(`  ${JSON.stringify(operationKey)}: { method: ${JSON.stringify(route.method)}; path: ${JSON.stringify(fullPath)}; input: ${inputType}; output: ${output} };`);
      group.set(
        methodName,
        `${JSON.stringify(methodName)}: (...[input]: OptionalIfEmpty<Operations[${JSON.stringify(operationKey)}]['input']>) => call<Operations[${JSON.stringify(operationKey)}]['output']>(${JSON.stringify(route.method)}, ${JSON.stringify(fullPath)}, input${isFormRoute(route) ? ', true' : ''})`,
      );
    }
  }

  const groupEntries = [...groups.entries()].map(([groupName, methods]) =>
    `    ${JSON.stringify(groupName)}: {\n${[...methods.values()].map((method) => `      ${method},`).join('\n')}\n    },`);

  return `// Generated by kivin. Typed HTTP client for this app.
// Only types are imported from the server code, so this file is safe to bundle into a frontend.
${renderer.render()}
/** Result of a handler as seen over HTTP: a raw \`Response\` carries no static type. */
/** \`HeadersInit\` is a DOM-lib name; this resolves under \`lib: ["ESNext"]\` too. */
type HeadersInput = NonNullable<ConstructorParameters<typeof Headers>[0]>;
type HandlerResult<T> = [Exclude<Awaited<T>, Response>] extends [never] ? unknown : Exclude<Awaited<T>, Response>;
/** \`{ key?: T }\` when every field of T is optional, otherwise \`{ key: T }\`. */
type Part<K extends string, T> = {} extends T ? { [P in K]?: T } : { [P in K]: T };
type OptionalIfEmpty<T> = {} extends T ? [input?: T] : [input: T];

export interface ClientRequestOptions {
  headers?: HeadersInput;
  signal?: AbortSignal;
}

export interface ClientOptions {
  /** Origin (and optional prefix) of the API, e.g. \`https://api.example.com\`. */
  baseUrl: string;
  /** Custom transport. Defaults to the global \`fetch\`; pass \`app.fetch\` to call an app in-process. */
  fetch?: (request: Request) => Response | Promise<Response>;
  /** Headers sent with every request; a function is evaluated per request (e.g. for auth tokens). */
  headers?: HeadersInput | (() => HeadersInput | Promise<HeadersInput>);
}

/** Thrown for non-2xx responses. \`body\` is the parsed JSON body when there is one, otherwise the text. */
export class KivinClientError extends Error {
  constructor(readonly status: number, readonly body: unknown, readonly response: Response) {
    super(\`Request failed with status \${status}\`);
    this.name = 'KivinClientError';
  }
}

/** Every route: HTTP method, path template, request input and success output. */
export interface Operations {
${operations.join('\n')}
}

export function createClient(options: ClientOptions) {
  const transport = options.fetch ?? ((request: Request) => fetch(request));
  const baseUrl = options.baseUrl.replace(/\\/+$/, '');

  async function call<TOutput>(
    method: string,
    path: string,
    input: { params?: Record<string, unknown>; query?: Record<string, unknown>; body?: unknown; headers?: HeadersInput; signal?: AbortSignal } = {},
    form = false,
  ): Promise<TOutput> {
    const resolvedPath = path.replace(/:([A-Za-z0-9_]+)/g, (_match, name: string) => {
      const value = input.params?.[name];
      if (value === undefined || value === null) {
        throw new TypeError(\`Missing path parameter "\${name}" for \${method} \${path}\`);
      }
      return encodeURIComponent(String(value));
    });
    const search = new URLSearchParams();
    for (const [key, value] of Object.entries(input.query ?? {})) {
      if (value === undefined || value === null) {
        continue;
      }
      for (const item of Array.isArray(value) ? value : [value]) {
        search.append(key, String(item));
      }
    }
    const queryString = search.toString();
    const headers = new Headers(typeof options.headers === 'function' ? await options.headers() : options.headers);
    new Headers(input.headers).forEach((value, key) => headers.set(key, value));
    const hasBody = input.body !== undefined;
    // Form routes (@Consumes multipart / urlencoded) send FormData; fetch sets the multipart boundary.
    const body = !hasBody ? undefined : form ? toFormBody(input.body) : JSON.stringify(input.body);
    if (hasBody && !form && !headers.has('content-type')) {
      headers.set('content-type', 'application/json');
    }

    const response = await transport(new Request(\`\${baseUrl}\${resolvedPath}\${queryString ? \`?\${queryString}\` : ''}\`, {
      method,
      headers,
      ...(body !== undefined ? { body } : {}),
      ...(input.signal ? { signal: input.signal } : {}),
    }));

    const text = method === 'HEAD' || response.status === 204 ? '' : await response.text();
    const isJson = (response.headers.get('content-type') ?? '').includes('json');
    const parsed: unknown = text === '' ? undefined : isJson ? JSON.parse(text) : text;
    if (!response.ok) {
      throw new KivinClientError(response.status, parsed, response);
    }
    return parsed as TOutput;
  }

  return {
${groupEntries.join('\n')}
  };
}

function toFormBody(value: unknown): NonNullable<RequestInit['body']> {
  if (value instanceof FormData || value instanceof URLSearchParams) {
    return value;
  }
  const formData = new FormData();
  for (const [key, field] of Object.entries((value ?? {}) as Record<string, unknown>)) {
    for (const item of Array.isArray(field) ? field : [field]) {
      if (item === undefined || item === null) {
        continue;
      }
      formData.append(key, item instanceof Blob ? item : String(item));
    }
  }
  return formData;
}

export type KivinClient = ReturnType<typeof createClient>;
`;

  function isFormRoute(route: AstRouteNode) {
    return route.consumes === 'multipart/form-data' || route.consumes === 'application/x-www-form-urlencoded';
  }

  function paramsType(route: AstRouteNode, fullPath: string, schema: string | undefined, infer: string) {
    if (schema) {
      return `${infer}<${schema}>`;
    }
    const names = [...fullPath.matchAll(/:([A-Za-z0-9_]+)/g)].map((match) => match[1]!);
    return names.length > 0 ? `{ ${names.map((name) => `${JSON.stringify(name)}: string | number`).join('; ')} }` : undefined;
  }

  function queryType(route: AstRouteNode, schema: string | undefined, infer: string) {
    if (schema) {
      return `${infer}<${schema}>`;
    }
    const reads = route.parameters.some((parameter) => parameter.source === 'query' || (parameter.source === 'input' && (parameter.fields ?? ['query']).includes('query')));
    return reads ? 'Record<string, string | string[] | undefined>' : undefined;
  }

  function bodyType(route: AstRouteNode, handler: string, schema: string | undefined, infer: string) {
    if (schema) {
      return `${infer}<${schema}>`;
    }
    const bodyParameter = route.parameters.find((parameter) => parameter.source === 'body');
    if (bodyParameter) {
      return `Parameters<${handler}>[${bodyParameter.index}]`;
    }
    const inputParameter = route.parameters.find((parameter) => parameter.source === 'input' && (parameter.fields ?? ['body']).includes('body'));
    return inputParameter ? `NonNullable<Parameters<${handler}>[0]>['body']` : undefined;
  }
}

function outputType(
  controller: AstControllerNode,
  route: AstRouteNode,
  handler: string,
  schemaType: (controller: AstControllerNode, expression: AstExpressionRef | undefined) => string | undefined,
  inferOutput: string,
) {
  const successes = route.responses.filter((response) => response.status >= 200 && response.status < 300);
  const withSchema = successes.filter((response) => response.schema);
  if (withSchema.length === 1) {
    const schema = schemaType(controller, withSchema[0]!.schema);
    if (schema) {
      return `${inferOutput}<${schema}>`;
    }
  }
  if (successes.length > 0 && successes.every((response) => response.status === 204)) {
    return 'void';
  }
  if (route.method === 'HEAD') {
    return 'void';
  }
  return `HandlerResult<ReturnType<${handler}>>`;
}

function clientName(controller: AstControllerNode, route: AstRouteNode): [string, string] {
  const fallbackGroup = lowerFirst(controller.className.replace(/Controller$/, '') || controller.className);
  if (route.operationId) {
    const dot = route.operationId.indexOf('.');
    if (dot > 0) {
      return [route.operationId.slice(0, dot), route.operationId.slice(dot + 1)];
    }
    return [fallbackGroup, route.operationId];
  }
  return [fallbackGroup, route.methodName];
}

function lowerFirst(value: string) {
  return value.charAt(0).toLowerCase() + value.slice(1);
}
